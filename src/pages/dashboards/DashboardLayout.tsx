interface DashboardLayoutProps {
  children: ReactNode;
  role: "admin" | "affiliate";
}

export function DashboardLayout({ children, role }: DashboardLayoutProps) {
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const location = useLocation();
  const navigate = useNavigate();
  const { signOut } = useAuth();
  const navItems = role === "admin" ? adminNav : affiliateNav;

  const handleSignOut = async () => {
    await signOut();
    navigate("/auth/signin");
  };

  return (
    <div className="bg-white min-h-screen patternbg">
      {/* Mobile sidebar backdrop */}
      {sidebarOpen && (
        <div
          className="fixed inset-0 bg-black/20 lg:hidden z-35"
          onClick={() => setSidebarOpen(false)}
        />
      )}
      {/* Sidebar */}
      <aside
        className={`
          fixed top-0 right-0 h-full 
          w-[80%] max-w-[320px] 
          bg-white border-slate-100 pt-20
          flex flex-col
          transition-transform duration-300 ease-in-out
          z-40
          ${sidebarOpen ? "translate-x-0" : "translate-x-full"}

          lg:left-0  lg:right-auto lg:w-64 lg:border-r lg:border-l-0 lg:translate-x-0
        `}
      >
        <nav className="p-4 space-y-1">
          {navItems.map((item) => {
            const isActive = location.pathname === item.path;
            return (
              <Link
                key={item.path}
                to={item.path}
                className={`flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium transition-colors ${
                  isActive
                    ? "bg-brand-50 text-brand-700"
                    : "text-slate-600 hover:bg-slate-100"
                }`}
                onClick={() => setSidebarOpen(false)}
              >
                {item.icon}
                {item.label}
              </Link>
            );
          })}
          

          <button
            className="flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium text-slate-600 hover:bg-slate-100 w-full mt-8"
            onClick={handleSignOut}
            >
            <svg
              className="w-5 h-5"
              fill="none"
              stroke="currentColor"
              viewBox="0 0 24 24"
              >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                strokeWidth={2}
                d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1"
                />
            </svg>
            Sign out
          </button>
        </nav>
      </aside>

      {/* Main content */}
      <div className="lg:pl-64 pt-15">
        <div className="flex items-center justify-between px-4 py-3 ">
          {/* MOBILE HAMBURGER */}
          <button
            className="lg:hidden text-blue-400"
            onClick={() => setSidebarOpen(true)}
          >
            See all pages
          </button>
        </div>
        <main className="p-4 md:pt-20 ">{children}</main>
      </div>
    </div>
  );
}
